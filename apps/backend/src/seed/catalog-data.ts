/** The collection a product belongs to when none is named explicitly. */
export function defaultCollection(
  p: Pick<ProductSpec, "type" | "gender" | "categories">,
): string | undefined {
  if (p.type === "Sports frames" || ["Cap", "Bag", "Socks", "Wristband"].includes(p.type))
    return undefined
  if (["Hoodie", "Sweatshirt", "Jacket"].includes(p.type)) return "layers-and-outerwear"
  return "performance-training"
}

